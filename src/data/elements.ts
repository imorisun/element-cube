function num(v: string): number | null {
  const s = v.trim()
  if (!s) return null
  const n = Number(s)
  return Number.isFinite(n) ? n : null
}

/** 计算元素在标准 18 列周期表中的网格位置 */
function computeGrid(item: {
  number: number
  category: string
  group: number | null
  period: number
}): { col: number; row: number } {
  // 行号说明：第 1 行为族号表头，第 2–8 行为周期 1–7，第 9 行为间隔，第 10/11 行为镧系与锕系
  if (item.category === 'lanthanide') {
    return { col: 3 + (item.number - 57), row: 10 }
  }
  if (item.category === 'actinide') {
    return { col: 3 + (item.number - 89), row: 11 }
  }
  return { col: item.group ?? 1, row: item.period + 1 }
}

export const ELEMENTS: ElementInfo[] = RAW.trim()
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => {
    const f = line.split('|')
    const item = {
      number: Number(f[0]),
      symbol: f[1],
      name: f[2],
      enName: f[3],
      mass: num(f[4]) ?? 0,
      category: f[5] as CategoryKey,
      group: num(f[6]),
      period: Number(f[7]),
      block: f[8] as ElementInfo['block'],
      electronConfig: f[9],
      shells: f[10].split(',').map(Number),
      phase: (f[11] || 'unknown') as Phase,
      melting: num(f[12]),
      boiling: num(f[13]),
      density: num(f[14]),
      electronegativity: num(f[15]),
      ionization: num(f[16]),
      radius: num(f[17]),
      discovered: f[18],
      discoverer: f[19],
      uses: f[20].split(';').map((s) => s.trim()),
      summary: f[21],
      synthetic: f[22] === '1',
    }
    return { ...item, grid: computeGrid(item) } as ElementInfo
  })

export const ELEMENT_BY_NUMBER: Record<number, ElementInfo> = Object.fromEntries(
  ELEMENTS.map((e) => [e.number, e]),
)

/** 常见同位素中子数（用于 3D 原子核演示），取最稳定/最常见同位素的质量数 */
export function massNumber(el: ElementInfo): number {
  return Math.round(el.mass)
}

